"use client";

import * as React from "react";
import { type DialogProps } from "@radix-ui/react-dialog";
import { Command as CommandPrimitive } from "cmdk";
import { Search } from "lucide-react";

import { cn } from "../../../../../lib/utils";
import { Dialog, DialogContent } from "./dialog";
import colors from "../../../../../lib/colors";

/**
 * Strategy:
 * - Set the important CSS custom properties inline on the Command root using values
 *   from lib/colors.ts so existing Tailwind utilities (bg-popover, text-muted-foreground,
 *   data-[selected=true]:bg-accent, etc.) keep working without relying on :root.
 * - Keep layout/spacing/animation classes intact.
 */

const Command = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive>
>(({ className, style, ...props }, ref) => {
  // inline CSS custom properties mapped to the tokens used by your system
  const cssVars: React.CSSProperties = {
    // core
    ["--background" as any]: colors.background,
    ["--foreground" as any]: colors.foreground,

    // popover (command palette surface)
    ["--popover" as any]: colors.popover,
    ["--popover-foreground" as any]: colors.popoverForeground,

    // muted / subtle text
    ["--muted-foreground" as any]: colors.mutedForeground,

    // accents & primary
    ["--accent" as any]: colors.accent,
    ["--accent-foreground" as any]: colors.accentForeground,
    ["--primary" as any]: colors.primary,
    ["--primary-foreground" as any]: colors.primaryForeground,

    // border / ring
    ["--border" as any]: colors.border,
    ["--ring" as any]: colors.ring,

    // allow callers to override any CSS var via style prop
    ...(style as React.CSSProperties),
  };

  return (
    <CommandPrimitive
      ref={ref}
      className={cn(
        "flex h-full w-full flex-col overflow-hidden rounded-md bg-popover text-popover-foreground",
        className
      )}
      style={cssVars}
      {...props}
    />
  );
});
Command.displayName = CommandPrimitive.displayName;

interface CommandDialogProps extends DialogProps {}

const CommandDialog = ({ children, ...props }: CommandDialogProps) => {
  return (
    <Dialog {...props}>
      <DialogContent className="overflow-hidden p-0 shadow-lg">
        {/* Keep the existing cmdk-specific utility selectors (they will now resolve via inline vars) */}
        <Command className="[&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group-heading]]:text-muted-foreground [&_[cmdk-group]:not([hidden])_~[cmdk-group]]:pt-0 [&_[cmdk-group]]:px-2 [&_[cmdk-input-wrapper]_svg]:h-5 [&_[cmdk-input-wrapper]_svg]:w-5 [&_[cmdk-input]]:h-12 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-3 [&_[cmdk-item]_svg]:h-5 [&_[cmdk-item]_svg]:w-5">
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  );
};

const CommandInput = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive.Input>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive.Input>
>(({ className, ...props }, ref) => (
  <div
    className="flex items-center px-3"
    // border-bottom using inline color var (Tailwind classes may not target this exact element),
    // so we set it explicitly here to be safe.
    style={{ borderBottom: `1px solid ${colors.border}` }}
    cmdk-input-wrapper=""
  >
    <Search
      className="mr-2 h-4 w-4 shrink-0"
      style={{ color: colors.mutedForeground, opacity: 0.8 }}
    />
    <CommandPrimitive.Input
      ref={ref}
      className={cn(
        "flex h-11 w-full rounded-md bg-transparent py-3 text-sm outline-none placeholder:text-muted-foreground disabled:cursor-not-allowed disabled:opacity-50",
        className
      )}
      {...props}
    />
  </div>
));
CommandInput.displayName = CommandPrimitive.Input.displayName;

