      restoredProductImages = chat.productImageDataUrls.map((dataUrl, idx) => 
        dataUrlToFile(dataUrl, `product_${idx}.jpg`)
      );
      console.log("✅ Restored", restoredProductImages.length, "product images from productImageDataUrls");
