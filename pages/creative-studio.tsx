  // Helper function to save poster silently (for automatic saving)
  async function savePosterToLibrary(posterUrl: string, index: number, silent: boolean = false): Promise<boolean> {
    if (!silent) {
      setSavingPoster(index);
    }
    try {
      // const token = await getAuthToken(); // TEMPORARILY DISABLED
      const token = null; // Temporarily disabled auth

      const headers: any = {
        "Content-Type": "application/json",
      };
      if (token) {
        headers.Authorization = `Bearer ${token}`;
      }

      // Check image size before sending (warn if too large)
      const imageSizeMB = posterUrl.length / 1024 / 1024;
      if (imageSizeMB > 8) {
        console.warn(`⚠️ Image size is ${imageSizeMB.toFixed(2)}MB, may cause issues`);
      }

      const response = await fetch("/api/creative-studio/save-poster", {
        method: "POST",
        headers: headers,
        body: JSON.stringify({
          imageUrl: posterUrl,
          name: `Creative Studio Poster ${index + 1}`,
          metadata: {
            brand: brand?.name,
            theme: config.theme,
            aspectRatio: config.aspectRatio,
            prompt: posterPrompt || "",
          },
        }),
      });

      // Handle 413 Payload Too Large error
      if (response.status === 413) {
        throw new Error("Image is too large to save. The image will still be available in your chat history.");
      }

      // Handle other non-OK responses
      if (!response.ok) {
        const errorText = await response.text();
        let errorMessage = "Failed to save poster";
        try {
          const errorJson = JSON.parse(errorText);
          errorMessage = errorJson.error || errorMessage;
        } catch {
          errorMessage = errorText || errorMessage;
        }
        throw new Error(errorMessage);
      }

      const result = await response.json();

      if (result.ok) {
        if (!silent) {
          setMessages((prev) => [
            ...prev,
            {
              id: generateMessageId(),
              role: "system",
              content: `Poster saved successfully! You can find it in your Image Library.`,
              timestamp: Date.now(),
            },
          ]);
        }
        return true;
      } else {
        throw new Error(result.error || "Failed to save poster");
      }
    } catch (error: any) {
      console.error("Save poster error:", error);
      if (!silent) {
        setMessages((prev) => [
          ...prev,
          {
            id: generateMessageId(),
            role: "system",
            content: `Failed to save poster: ${error.message || "Unknown error"}`,
            timestamp: Date.now(),
          },
        ]);
      }
      return false;
    } finally {
      if (!silent) {
        setSavingPoster(null);
      }
    }
  }

