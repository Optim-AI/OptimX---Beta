  async function fileToDataUrl(file: File): Promise<string> {
    return new Promise((resolve, reject) => {
      // Check file size first (5MB limit to avoid stack overflow)
      const maxSize = 5 * 1024 * 1024; // 5MB
      if (file.size > maxSize) {
        console.warn(`⚠️ Image is ${(file.size / 1024 / 1024).toFixed(2)}MB, compressing...`);
        // Compress the image
        compressImage(file, maxSize)
          .then((compressed) => {
            const reader = new FileReader();
            reader.onload = () => resolve(String(reader.result));
            reader.onerror = (err) => reject(err);
            reader.readAsDataURL(compressed);
          })
          .catch((err) => {
            console.error("Compression failed, using original:", err);
            // Fallback to original if compression fails
            const reader = new FileReader();
            reader.onload = () => resolve(String(reader.result));
            reader.onerror = (err) => reject(err);
            reader.readAsDataURL(file);
          });
      } else {
        const reader = new FileReader();
        reader.onload = () => resolve(String(reader.result));
        reader.onerror = (err) => reject(err);
        reader.readAsDataURL(file);
      }
    });
  }

  // Compress image to reduce size
  function compressImage(file: File, maxSizeBytes: number): Promise<File> {
    return new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = (e) => {
        const img = new Image();
        img.onload = () => {
          const canvas = document.createElement("canvas");
          let width = img.width;
          let height = img.height;
          
          // Calculate new dimensions (max 2000px on longest side)
          const maxDimension = 2000;
          if (width > height && width > maxDimension) {
            height = (height * maxDimension) / width;
            width = maxDimension;
          } else if (height > maxDimension) {
            width = (width * maxDimension) / height;
            height = maxDimension;
          }
          
          canvas.width = width;
          canvas.height = height;
          const ctx = canvas.getContext("2d");
          if (!ctx) {
            reject(new Error("Could not get canvas context"));
            return;
          }
          
          ctx.drawImage(img, 0, 0, width, height);
          
          // Try different quality levels until we're under the size limit
          let quality = 0.9;
          const tryCompress = () => {
            canvas.toBlob(
              (blob) => {
                if (!blob) {
                  reject(new Error("Failed to compress image"));
                  return;
                }
                
                if (blob.size <= maxSizeBytes || quality <= 0.1) {
                  const compressedFile = new File([blob], file.name, {
                    type: "image/jpeg",
                    lastModified: Date.now(),
                  });
                  console.log(`✅ Compressed image: ${(file.size / 1024 / 1024).toFixed(2)}MB → ${(blob.size / 1024 / 1024).toFixed(2)}MB`);
                  resolve(compressedFile);
                } else {
                  quality -= 0.1;
                  tryCompress();
                }
              },
              "image/jpeg",
              quality
            );
          };
          
          tryCompress();
        };
        img.onerror = () => reject(new Error("Failed to load image"));
        img.src = e.target?.result as string;
      };
      reader.onerror = () => reject(new Error("Failed to read file"));
      reader.readAsDataURL(file);
    });
  }

  // Fetch images from URL and convert to File objects (via API route to avoid CORS)
  // Returns multiple images if product link, single image if direct image URL
  async function fetchImageFromUrl(url: string): Promise<{ images: File[]; productName?: string; description?: string; price?: string }> {
    try {
      // Use API route to fetch image server-side (bypasses CORS)
      const response = await fetch("/api/creative-studio/fetch-image", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({ url }),
      });

      const result = await response.json();

      if (!response.ok || !result.ok) {
        throw new Error(result.error || `Failed to fetch image: ${response.statusText}`);
      }

      // Handle multiple images (product link) - API now returns data URLs
      if (result.isMultiple && Array.isArray(result.images)) {
        const imageFiles: File[] = [];
        for (const dataUrl of result.images) {
          try {
            // API now returns data URLs, so convert directly to File
            if (!dataUrl.startsWith('data:')) {
              console.warn('Expected data URL but got:', dataUrl.substring(0, 50));
              continue;
            }
            
            const m = dataUrl.match(/^data:(.+);base64,(.+)$/);
            if (!m) {
              console.warn('Invalid data URL format');
              continue;
            }
            
            const contentType = m[1] || 'image/jpeg';
            const base64Data = m[2];
            
            // Convert base64 to binary
            const binaryString = atob(base64Data);
            const bytes = new Uint8Array(binaryString.length);
            for (let i = 0; i < binaryString.length; i++) {
              bytes[i] = binaryString.charCodeAt(i);
            }
            const blob = new Blob([bytes], { type: contentType });
            
            // Determine file extension
            let extension = 'jpg';
            if (contentType.includes('png')) extension = 'png';
            else if (contentType.includes('gif')) extension = 'gif';
            else if (contentType.includes('webp')) extension = 'webp';
            else if (contentType.includes('svg')) extension = 'svg';
            
            const file = new File([blob], `product_${Date.now()}_${imageFiles.length}.${extension}`, { type: contentType });
            imageFiles.push(file);
          } catch (e) {
            console.warn(`Failed to convert data URL to File:`, e);
          }
        }
        
        console.log("✅ Converted product images to Files:", { count: imageFiles.length });
        
        return {
          images: imageFiles,
          productName: result.productName,
          description: result.description,
          price: result.price,
        };
      }

      // Handle single image (direct image URL or fallback)
      const dataUrl = result.dataUrl;
      const contentType = result.contentType || 'image/jpeg';
      
      // Extract base64 data
      const base64Data = dataUrl.split(',')[1];
      const binaryString = atob(base64Data);
      const bytes = new Uint8Array(binaryString.length);
      for (let i = 0; i < binaryString.length; i++) {
        bytes[i] = binaryString.charCodeAt(i);
      }
      const blob = new Blob([bytes], { type: contentType });

      // Determine file extension from content type
      let extension = 'jpg';
      if (contentType.includes('png')) extension = 'png';
      else if (contentType.includes('gif')) extension = 'gif';
      else if (contentType.includes('webp')) extension = 'webp';
      else if (contentType.includes('svg')) extension = 'svg';
      else {
        // Try to extract from URL
        const fileName = url.split('/').pop() || '';
        if (fileName.includes('.')) {
          const urlExt = fileName.split('.').pop()?.toLowerCase();
          if (urlExt && ['jpg', 'jpeg', 'png', 'gif', 'webp', 'svg'].includes(urlExt)) {
            extension = urlExt;
          }
        }
      }

      const file = new File([blob], `fetched_${Date.now()}.${extension}`, { type: contentType });
      return { images: [file] };
    } catch (error: any) {
      console.error("Error fetching image from URL:", error);
      throw new Error(`Could not fetch image from URL: ${error.message || "Unknown error"}`);
    }
  }

  // Check if text contains a URL
  function containsUrl(text: string): string | null {
    const urlRegex = /(https?:\/\/[^\s]+)/g;
    const match = text.match(urlRegex);
    return match ? match[0] : null;
  }

  // Check if URL points to an image
  function isImageUrl(url: string): boolean {
    const imageExtensions = /\.(jpg|jpeg|png|gif|webp|svg|bmp)(\?.*)?$/i;
    return imageExtensions.test(url) || url.includes('image') || url.includes('img');
  }

