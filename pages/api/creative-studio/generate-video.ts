// Helper function to parse data URL and extract image bytes and mime type
function parseDataUrl(dataUrl: string): { imageBytes: string; mimeType: string } | null {
  if (!dataUrl || typeof dataUrl !== "string") return null;
  
  // Match data URL format: data:[<mediatype>][;base64],<data>
  const match = dataUrl.match(/^data:([^;]+);base64,(.+)$/);
  if (!match) return null;
  
  return {
    mimeType: match[1],
    imageBytes: match[2],
  };
}

// Helper function to create a reference image object for Veo 3.1
function createReferenceImage(dataUrl: string, referenceType: "asset" | "style" = "asset") {
  const parsed = parseDataUrl(dataUrl);
  if (!parsed) return null;
  
  return {
    image: {
      imageBytes: parsed.imageBytes,
      mimeType: parsed.mimeType,
    },
    referenceType,
  };
}

